def get_position_lead(position: str) -> str:
    """Возвращает контекстную вводную фразу для позиции расклада."""
    pos_lower = position.lower()
    for key, phrase in POSITION_LEADS.items():
        if key in pos_lower:
            return phrase
    return "здесь открывается"


def rich_card_text(card: dict, rev: bool, position: str, index: int, compact: bool = False) -> str:
    """
    Формирует живое, человеческое описание карты в контексте позиции.
    compact=True — для больших раскладов (6+ карт), без полной истории.
    """
    orientation = "🔄 перевёрнутая" if rev else "⬆️ прямая"
    meaning = card["reversed"] if rev else card["upright"]
    story = card.get("story", "")
    advice = card.get("advice", "")
    pos_lead = get_position_lead(position)

    # Перевёрнутая карта — дополнительное пояснение
    rev_note = ""
    if rev:
        rev_note = (
            "\n\n⚠️ _Карта перевёрнута — эта энергия заблокирована или выражается в избытке. "
            "Возможно, вы сдерживаете то, что хочет проявиться, или, наоборот, "
            "слишком давите на эту тему. Это сигнал: пора взглянуть честно._"
        )

    if compact:
        # Компактный вариант: без полной истории, но с живым контекстом
        return (
            f"\n*{index}. {position}*\n\n"
            f"{card.get('emoji','🃏')} *{card['name']}* ({card['num']}) — _{orientation}_\n\n"
            f"В позиции «{position}» {pos_lead} энергия *{meaning.split(',')[0].strip()}*. "
            f"{meaning}."
            f"{rev_note}\n\n"
            f"🎯 _{advice}_"
        )
    else:
        # Полный вариант: с историей карты и глубоким контекстом
        return (
            f"\n*{index}. {position}*\n\n"
            f"{card.get('emoji','🃏')} *{card['name']}* ({card['num']}) — _{orientation}_\n\n"
            f"📖 _{story}_\n\n"
            f"В позиции «{position}» {pos_lead} энергия *{meaning.split(',')[0].strip()}*. "
            f"{meaning}."
            f"{rev_note}\n\n"
            f"🎯 _{advice}_"
        )


def synthesize_reading(spread_name: str, positions: list, cards: list) -> str:
    """
    Генерирует живой итоговый синтез всего расклада — что все карты говорят вместе.
    """
    n = len(cards)
    if n == 1:
        card, rev = cards[0]
        return card.get("advice", "Доверяйте посланию этой карты.")

    major_ids = {m["id"] for m in MAJOR_ARCANA}
    major_count = sum(1 for c, r in cards if c.get("id") in major_ids)
    reversed_count = sum(1 for _, r in cards if r)
    positive_count = sum(1 for c, r in cards if (c.get("yes_weight", 0) > 0 and not r) or (c.get("yes_weight", 0) < 0 and r))

    first_card, first_rev = cards[0]
    last_card, last_rev = cards[-1]
    first_meaning = (first_card["reversed"] if first_rev else first_card["upright"]).split(",")[0].strip().lower()
    last_meaning = (last_card["reversed"] if last_rev else last_card["upright"]).split(",")[0].strip().lower()

    # ── Вводная — общий тон расклада ──────────────────────
    if major_count >= n * 0.6:
        intro = (
            f"В этом раскладе {major_count} из {n} карт — Старшие Арканы. "
            "Это редкое и значимое стечение: вселенная буквально кричит о том, "
            "что происходящее несёт глубокий, судьбоносный смысл. "
            "Это не просто бытовой вопрос — это момент, который изменит вас."
        )
    elif reversed_count > n // 2:
        intro = (
            f"Большинство карт ({reversed_count} из {n}) легло перевёрнутыми — "
            "расклад говорит о периоде внутренней работы. "
            "Не всё то, что кажется застревшим снаружи, заблокировано навсегда: "
            "часто перевёрнутые карты — это приглашение остановиться и честно посмотреть внутрь."
        )
    elif positive_count >= n * 0.6:
        intro = (
            "Расклад в целом наполнен поддерживающей энергией — "
            "большинство карт несут открытые, конструктивные вибрации. "
            "Это не значит, что всё будет легко, но направление верное."
        )
    else:
        intro = (
            "Расклад рисует объёмную, неоднозначную картину — "
            "в ней есть и свет, и тени, и вызовы, и возможности. "
            "Именно такой и бывает настоящая жизнь."
        )

    # ── Дуга от начала к концу ────────────────────────────
    if first_rev and not last_rev:
        arc = (
            f"Путь начинается с трудностей ({first_card['name']} — {first_meaning}), "
            f"но финальная карта {last_card['name']} открывает перспективу {last_meaning}. "
            "Это обнадёживающая дуга: из сложности — к ресурсу."
        )
    elif not first_rev and last_rev:
        arc = (
            f"Начало сильное ({first_card['name']} — {first_meaning}), "
            f"однако финальная карта {last_card['name']} в перевёрнутом положении предупреждает: "
            "не расслабляйтесь раньше времени — потребуется осознанность."
        )
    elif last_card.get("yes_weight", 0) > 0 and not last_rev:
        arc = (
            f"История разворачивается от «{positions[0]}» ({first_card['name']}: {first_meaning}) "
            f"к «{positions[-1]}» ({last_card['name']}: {last_meaning}). "
            "Финальная карта светлая — ситуация движется в правильном направлении."
        )
    else:
        arc = (
            f"От «{positions[0]}» с картой {first_card['name']} ({first_meaning}) "
            f"к «{positions[-1]}» с картой {last_card['name']} ({last_meaning}): "
            "расклад указывает на необходимость взвешенного, внимательного подхода."
        )

    # ── Итоговый совет ────────────────────────────────────
    # Берём совет из финальной карты (исход — самый весомый)
    key_advice = last_card.get("advice", "")
    if not key_advice and len(cards) > 1:
        # Или из середины расклада
        mid = cards[n // 2][0]
        key_advice = mid.get("advice", "")

    advice_text = f"*Главное послание этого расклада:* {key_advice}" if key_advice else ""

    return f"{intro}\n\n{arc}\n\n{advice_text}"


