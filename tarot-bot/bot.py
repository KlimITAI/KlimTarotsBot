def _make_minor_suit(suit_en, suit_ru, suit_emoji, element_ru, rank_data):
    cards = []
    rank_names = [
        ("Туз", "A"), ("Двойка", "2"), ("Тройка", "3"), ("Четвёрка", "4"),
        ("Пятёрка", "5"), ("Шестёрка", "6"), ("Семёрка", "7"),
        ("Восьмёрка", "8"), ("Девятка", "9"), ("Десятка", "10"),
        ("Паж", "P"), ("Рыцарь", "Kn"), ("Королева", "Q"), ("Король", "K"),
    ]
    for i, (rank_ru, rank_code) in enumerate(rank_names):
        d = rank_data[i]
        cards.append({
            "id": f"{suit_en}_{rank_code}",
            "name": f"{rank_ru} {suit_ru}",
            "num": f"{rank_code} {suit_emoji}",
            "emoji": suit_emoji,
            "element": element_ru,
            "upright": d[0],
            "reversed": d[1],
            "story": d[2],
            "advice": d[3],
            "yes_weight": d[4],
        })
    return cards

