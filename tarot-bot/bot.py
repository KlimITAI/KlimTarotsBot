async def do_spread(query, spread_key: str):
    if spread_key == "card_of_day":
        await do_card_of_day(query)
        return

    if spread_key not in SPREADS:
        await safe_edit(query, "❌ Расклад не найден.")
        return

    uid = query.from_user.id
    spread = SPREADS[spread_key]
    n = len(spread["positions"])
    cards = draw_cards(n)

    # Сохранить в историю
    user_history[uid].append({
        "type": spread["name"],
        "cards": [c["name"] for c, _ in cards],
        "time": datetime.now(MSK_TZ).strftime("%d.%m %H:%M"),
    })

    # ── Строим текст результата ──────────────────────────
    compact = n > 5  # для больших раскладов — компактный формат карт

    header = (
        f"✨ *{spread['name']}*\n"
        f"_{spread['desc']}_\n\n"
        f"🌿 _{spread['intro']}_\n\n"
        f"{'━' * 26}"
    )

    # Карточные блоки
    card_blocks = []
    for i, (pos, (card, rev)) in enumerate(zip(spread["positions"], cards), 1):
        card_blocks.append(rich_card_text(card, rev, pos, i, compact=compact))

    # Синтез всего расклада
    synthesis = synthesize_reading(spread["name"], spread["positions"], cards)
    synthesis_block = (
        f"\n{'━' * 26}\n\n"
        f"🔮 *Что всё это значит вместе*\n\n"
        f"{synthesis}"
    )

    keyboard = back_to_main()

    # ── Отправка с учётом лимита Telegram 4096 символов ──
    # Шапка всегда первая
    await safe_edit(query, header)

    # Карты — порционно, каждая как отдельное сообщение если нужно
    chunk = ""
    for block in card_blocks:
        if len(chunk) + len(block) > 3800:
            await query.message.reply_text(chunk, parse_mode=ParseMode.MARKDOWN)
            chunk = block
        else:
            chunk += "\n" + block

    if chunk:
        # Последний чанк карт — без синтеза, если синтез не влезет
        if len(chunk) + len(synthesis_block) <= 3900:
            await query.message.reply_text(
                chunk + synthesis_block,
                reply_markup=keyboard,
                parse_mode=ParseMode.MARKDOWN,
            )
        else:
            await query.message.reply_text(chunk, parse_mode=ParseMode.MARKDOWN)
            await query.message.reply_text(
                synthesis_block,
                reply_markup=keyboard,
                parse_mode=ParseMode.MARKDOWN,
            )
    else:
        await query.message.reply_text(
            synthesis_block,
            reply_markup=keyboard,
            parse_mode=ParseMode.MARKDOWN,
        )


