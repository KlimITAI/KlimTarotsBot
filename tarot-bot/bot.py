def escape_md(text: str) -> str:
    """Экранирует спецсимволы Markdown v1 в пользовательских именах."""
    for ch in ("_", "*", "`", "["):
        text = text.replace(ch, f"\\{ch}")
    return text


async def safe_answer(query, text: str | None = None, show_alert: bool = False):
    """Безопасно отвечает на callback_query, не падая на просроченных запросах."""
    try:
        await query.answer(text=text, show_alert=show_alert)
    except BadRequest as exc:
        logger.debug("Ignoring callback answer error: %s", exc)


async def safe_edit(query, text: str, reply_markup=None, parse_mode=ParseMode.MARKDOWN):
    """Безопасно редактирует сообщение: игнорирует 'Message is not modified', обрабатывает медиа-сообщения и fallback на plain text."""
    try:
        await query.edit_message_text(
            text,
            reply_markup=reply_markup,
            parse_mode=parse_mode,
        )
    except BadRequest as exc:
        msg = str(exc)
        if "Message is not modified" in msg:
            return
        if "There is no text in the message to edit" in msg:
            await query.message.reply_text(
                text,
                reply_markup=reply_markup,
                parse_mode=parse_mode,
            )
            return
        if "Can't parse entities" in msg and parse_mode is not None:
            await query.edit_message_text(text, reply_markup=reply_markup)
            return
        raise

